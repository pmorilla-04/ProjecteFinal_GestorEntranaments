    private void carregarIntensitats() {

        cbmIntensitat.removeAllItems();
        cbmIntensitat.addItem(null);
        try {

            ResultSet rs = Querys.getIntensitats();

            if (rs.next()) {

                String enumValue = rs.getString(2);

                enumValue = enumValue
                        .replace("enum(", "")
                        .replace(")", "")
                        .replace("'", "");

                String[] values = enumValue.split(",");

                for (String v : values) {
                    cbmIntensitat.addItem(v.trim());
                    GestiorFitxersTXT.escripturaAFitxerLog("Carraguem Intensitats");
                }
            }

        } catch (SQLException e) {
            e.printStackTrace();
        }
    }

    private void carregarTipusEsport() {

        cbmTipus.removeAllItems();
        cbmTipus.addItem(null);

        try {
            ResultSet rs = Querys.getTipusEsport();

            while (rs.next()) {
                int id = rs.getInt("id");
                String nom = rs.getString("nom");

                cbmTipus.addItem(new TipusEsport(id, nom));
                GestiorFitxersTXT.escripturaAFitxerLog("Carreguem id tipus esport");
            }

        } catch (SQLException e) {
            e.printStackTrace();
        }
    }

    public void omplirTaulaEntrenaments() {

        String[] columnes = {
            "ID", "DATA", "DURADA", "DISTANCIA",
            "DESCRIPCIO", "INTENSITAT", "COMPLETAT",
            "ID_USUARI", "ID_TIPUS"
        };

        javax.swing.table.DefaultTableModel model
                = new javax.swing.table.DefaultTableModel();

        model.setColumnIdentifiers(columnes);

        for (MODEL.Entrenament e : CONTROLLER.Principal.entrenaments) {

            Object[] fila = {
                e.getId(),
                e.getData(),
                e.getDuradaMinuts(),
                e.getDistancia(),
                e.getDescripcio(),
                e.getIntensitat(),
                e.isCompletat(),
                e.getUsuariId(),
                e.getTipusEsportId()
            };

            model.addRow(fila);
        }

        tblEntranaments.setModel(model);
        GestiorFitxersTXT.escripturaAFitxerLog("Omplint taula entrenaments");
    }
    
       public void omplirTaulaComentaris() {

        String[] columnes = {
            "ID",
            "TEXT",
            "DATA",
            "ENTRENAMENT_ID",
            "ENTRENADOR_ID"
        };

        DefaultTableModel model = new DefaultTableModel();

        model.setColumnIdentifiers(columnes);

        for (Comentari c : CONTROLLER.Principal.comentaris) {

            Object[] fila = {
                c.getId(),
                c.getText(),
                c.getData(),
                c.getEntrenamentId(),
                c.getEntrenadorId()
            };

            model.addRow(fila);
        }

        tblComentaris.setModel(model);
    }


