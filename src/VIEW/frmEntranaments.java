private void carregarIntensitats() {

        cbmIntensitat.removeAllItems();
        cbmIntensitat.addItem(null);
        try {

            ResultSet rs = Querys.getIntensitats();

            if (rs.next()) {

                String enumValue = rs.getString(2);

                enumValue = enumValue
                        .replace("enum(", "")
                        .replace(")", "")
                        .replace("'", "");

                String[] values = enumValue.split(",");

                for (String v : values) {
                    cbmIntensitat.addItem(v.trim());
                    GestiorFitxersTXT.escripturaAFitxerLog("carreguem les intensitats al combo box");
                }
            }

        } catch (SQLException e) {
            e.printStackTrace();
        }
    }

    private void carregarTipusEsport() {

        cbmTipus.removeAllItems();
        cbmTipus.addItem(null);
        try {

            ResultSet rs = Querys.getTipusEsport();

            while (rs.next()) {

                int id = rs.getInt("id");
                String nom = rs.getString("nom");

                cbmTipus.addItem(new TipusEsport(id, nom));
                GestiorFitxersTXT.escripturaAFitxerLog("Carraguem els id del tipus d'esport al combo box");
            }

        } catch (SQLException e) {
            e.printStackTrace();
        }
    }
